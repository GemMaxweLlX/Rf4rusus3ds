"""Типографика русского текста по правилам перевода (Tolma4 Team / Lazy Games).

fix(s) -> s. Служебные метки ＠…＠, ＋, %s/%d, ''…'' (кавычки игры) и переносы строк не трогаются.
Что исправляется:
  - знаки препинания, которых нет в русском: ,... ...? ...! !? ??? и т. п.;
  - пробел перед знаком препинания;
  - точка перед закрывающей кавычкой: «Текст.» -> «Текст».;
  - звукоподражания через дефис: Ааа -> А-а-а, Хммм -> Хм-м-м;
  - окончания порядковых числительных: 5-ый -> 5-й, 5-ого -> 5-го;
  - «бог» в устойчивых оборотах: слава Богу -> слава богу;
  - прописное «Вы» посреди фразы -> «вы»;
  - прямые кавычки "…" -> «…»;
  - буква Ё в словах, где без неё не бывает: еще, ее, нее, черт, пошел, мое...
"""
import re

TOKEN = re.compile(r"＠[^＠]*＠|''|%[-+ 0-9.]*[sd]|[-]")
CYR = 'А-Яа-яЁё'

def _protect(s):
    keep = []
    def sub(m):
        keep.append(m.group(0))
        return '\x00%d\x01' % (len(keep) - 1)
    return TOKEN.sub(sub, s), keep

def _restore(s, keep):
    return re.sub('\x00(\\d+)\x01', lambda m: keep[int(m.group(1))], s)

YO = [  # слова, которые пишутся только через ё
    (r'еще', 'ещё'), (r'ее', 'её'), (r'нее', 'неё'), (r'черт', 'чёрт'), (r'чертов', 'чёртов'),
    (r'чертова', 'чёртова'), (r'чертово', 'чёртово'), (r'шел', 'шёл'), (r'пошел', 'пошёл'),
    (r'нашел', 'нашёл'), (r'пришел', 'пришёл'), (r'ушел', 'ушёл'), (r'зашел', 'зашёл'),
    (r'вошел', 'вошёл'), (r'прошел', 'прошёл'), (r'подошел', 'подошёл'), (r'вышел', 'вышел'),
    (r'мое', 'моё'), (r'твое', 'твоё'), (r'свое', 'своё'), (r'вдвоем', 'вдвоём'), (r'втроем', 'втроём'),
    (r'идет', 'идёт'), (r'придет', 'придёт'), (r'пойдет', 'пойдёт'), (r'найдет', 'найдёт'),
    (r'дает', 'даёт'), (r'знает', 'знает'), (r'живет', 'живёт'), (r'ждет', 'ждёт'),
    (r'зовет', 'зовёт'), (r'несет', 'несёт'), (r'растет', 'растёт'), (r'ведет', 'ведёт'),
    (r'тяжелый', 'тяжёлый'), (r'темный', 'тёмный'), (r'зеленый', 'зелёный'), (r'желтый', 'жёлтый'),
    (r'черный', 'чёрный'), (r'теплый', 'тёплый'), (r'веселый', 'весёлый'), (r'надежный', 'надёжный'),
]
YO = [(a, b) for a, b in YO if a != b]
YO_RE = [(re.compile(r'(?<![%s])%s(?![%s])' % (CYR, a, CYR)), b) for a, b in YO] + \
        [(re.compile(r'(?<![%s])%s(?![%s])' % (CYR, a[0].upper() + a[1:], CYR)), b[0].upper() + b[1:]) for a, b in YO]

GOD = [('слава Богу', 'слава богу'), ('ради Бога', 'ради бога'), ('не дай Бог', 'не дай бог'),
       ('Бог знает', 'бог знает'), ('Бог его знает', 'бог его знает'), ('ей-Богу', 'ей-богу'),
       ('Боже мой', 'боже мой'), ('Бог с ним', 'бог с ним'), ('Бог с тобой', 'бог с тобой')]

def fix(s):
    if not isinstance(s, str) or not re.search('[%s]' % CYR, s):
        return s
    t, keep = _protect(s)
    # прямые кавычки -> ёлочки (только парные, в строке без служебных кавычек)
    if t.count('"') % 2 == 0 and t.count('"'):
        t = re.sub(r'"([^"\n]*)"', r'«\1»', t)
    # знаки препинания
    t = re.sub(r',\s*\.{2,}', '...', t)            # ,... ,.. -> ...
    t = re.sub(r'\.{3},', '...', t)                 # ..., -> ...
    t = re.sub(r'(?<!\.)\.\.,', '...', t)           # .., -> ...
    t = re.sub(r'\.{3}\?!+', '?!.', t)              # ...?! -> ?!.
    t = re.sub(r'\.{3}\?', '?..', t)                # ...? -> ?..
    t = re.sub(r'\.{3}!', '!..', t)                 # ...! -> !..
    def run(m):
        r = m.group(0)
        if '?' in r: return '?' + '!' * min(2, r.count('!'))
        return '!' * min(3, len(r))
    t = re.sub(r'(?<=[%s\x01»)])[!?]{2,}' % CYR, run, t)   # одиночное «???» (неизвестно) не трогаем
    # пробел перед знаком препинания (кроме многоточия в начале фразы)
    t = re.sub(r'(?<=[%s0-9»)\x01]) +([,.;:!?])(?!\.\.)' % CYR, r'\1', t)
    # точка перед закрывающей ёлочкой
    t = re.sub(r'(?<![.?!])\.»', '».', t)
    # звукоподражания: три и больше одинаковых кириллических букв подряд
    t = re.sub(r'([%s])\1{2,}' % CYR, lambda m: '-'.join(m.group(0)), t, flags=re.I)
    # порядковые числительные
    t = re.sub(r'(\d)-(ый|ой|ий)(?![%s])' % CYR, r'\1-й', t)
    t = re.sub(r'(\d)-(ая|яя)(?![%s])' % CYR, r'\1-я', t)
    t = re.sub(r'(\d)-(ое|ее|ые|ие)(?![%s])' % CYR, r'\1-е', t)
    t = re.sub(r'(\d)-(ым|ом|им)(?![%s])' % CYR, r'\1-м', t)
    t = re.sub(r'(\d)-(ых|их)(?![%s])' % CYR, r'\1-х', t)
    t = re.sub(r'(\d)-(ого|его)(?![%s])' % CYR, r'\1-го', t)
    t = re.sub(r'(\d)-(ому|ему)(?![%s])' % CYR, r'\1-му', t)
    # бог в устойчивых оборотах (не в начале фразы)
    for a, b in GOD:
        t = re.sub(r'(?<=[%s,] )' % CYR + re.escape(a), b, t)
    # прописное Вы посреди фразы
    t = re.sub(r'(?<=[%s,;:] )(Вы|Вас|Вам|Вами|Ваш|Ваша|Ваше|Ваши|Вашего|Вашей|Вашему|Вашим|Вашими|Вашу|Ваших)(?![%s])' % (CYR, CYR),
               lambda m: m.group(1).lower(), t)
    # ё
    for rx, b in YO_RE:
        t = rx.sub(b, t)
    return _restore(t, keep)
